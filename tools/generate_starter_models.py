"""Make three small, original textured GLB demonstration assets for Hush Hunt.
These are identifiable 3D prototype meshes, NOT photogrammetry / photographic 3D scans.
Use a species-specific licensed GLB to replace them for true photorealism.
Requires trimesh, numpy, Pillow. All originals made in this script, CC0.
"""
from pathlib import Path
import math, numpy as np, trimesh
from PIL import Image, ImageDraw, ImageFilter
from trimesh.visual.texture import TextureVisuals
from trimesh.visual.material import SimpleMaterial
out = Path(__file__).resolve().parents[1] / 'WhiskerHunt/Resources/Raw/ar_models'
out.mkdir(parents=True,exist_ok=True)
rng = np.random.default_rng(99)

def tex(base, kind, size=768):
    y,x=np.mgrid[0:size,0:size]; u=x/size;v=y/size
    noise=np.asarray(Image.fromarray(rng.integers(0,255,(size//8,size//8),dtype=np.uint8)).resize((size,size),Image.Resampling.BICUBIC),dtype=np.float32)/255-.5
    if kind=='shell':
        bands=(np.sin(2*np.pi*(u*14+0.06*np.sin(v*24)+v*.34))*.5+.5)
        fine=(np.sin(u*2*np.pi*99+v*2*np.pi*3)*.5+.5)
        r=base[0]+noise*19-bands*68+fine*8;g=base[1]+noise*14-bands*40+fine*5;b=base[2]+noise*12-bands*23+fine*4
    elif kind=='skin':
        pores=(np.sin(u*2*np.pi*210)*np.cos(v*2*np.pi*131))
        r=base[0]+noise*22+pores*4;g=base[1]+noise*19+pores*5;b=base[2]+noise*17+pores*4
    elif kind=='red':
        r=base[0]+noise*22;g=base[1]+noise*13;b=base[2]+noise*11
    else:
        r=np.full_like(u,base[0]);g=np.full_like(u,base[1]);b=np.full_like(u,base[2])
    a=np.stack([r,g,b],axis=-1).clip(0,255).astype(np.uint8)
    return Image.fromarray(a,'RGB')

def mesh_uv_sphere(center, radii, img, count=(72,42), warp=None):
    # UVs with duplicative seam vertices, normals generated by trimesh.
    seg,stacks=count; vertices=[]; uv=[];faces=[]
    for j in range(stacks+1):
        t=math.pi*j/stacks
        for i in range(seg+1):
            p=math.pi*2*i/seg
            coords=np.array([math.sin(t)*math.cos(p),math.cos(t),math.sin(t)*math.sin(p)])
            if warp:coords=warp(coords)
            vertices.append(np.asarray(center)+np.asarray(radii)*coords)
            uv.append((i/seg,1-j/stacks))
    for j in range(stacks):
        for i in range(seg):
            a=j*(seg+1)+i;b=a+seg+1
            faces.extend([[a,b,a+1],[a+1,b,b+1]])
    m=trimesh.Trimesh(vertices=np.array(vertices),faces=faces,process=False)
    m.visual=TextureVisuals(uv=np.array(uv),material=SimpleMaterial(image=img, diffuse=[255,255,255,255]))
    return m

def solid_sphere(center, radii, img): return mesh_uv_sphere(center,radii,img,(40,24))

def tapered_tube(points, radii, image, segments=20):
    pts=np.asarray(points,dtype=np.float64); vertices=[];uv=[];faces=[]
    for j,p in enumerate(pts):
        tangent=pts[min(j+1,len(pts)-1)]-pts[max(0,j-1)]
        tangent=tangent/(np.linalg.norm(tangent)+1e-10)
        cross=np.cross(tangent,[0,0,1])
        if np.linalg.norm(cross)<.001:cross=np.cross(tangent,[0,1,0])
        cross/=np.linalg.norm(cross)
        binormal=np.cross(tangent,cross)
        for i in range(segments+1):
            t=2*math.pi*i/segments
            v=p+radii[j]*(cross*math.cos(t)+binormal*math.sin(t))
            vertices.append(v);uv.append((i/segments,j/(len(pts)-1)))
    for j in range(len(pts)-1):
        for i in range(segments):
            a=j*(segments+1)+i;b=a+segments+1
            faces.extend([[a,a+1,b],[a+1,b+1,b]])
    m=trimesh.Trimesh(vertices=np.array(vertices),faces=faces,process=False)
    m.visual=TextureVisuals(uv=np.array(uv),material=SimpleMaterial(image=image, diffuse=[255,255,255,255]));return m

def add(scene,mesh,name):scene.add_geometry(mesh,geom_name=name)

def snail(filename,amber=False):
    body=tex((153,115,69) if amber else (143,122,103),'skin')
    light=tex((179,143,94) if amber else (165,144,127),'skin')
    shell=tex((207,145,51) if amber else (185,156,109),'shell')
    dark=tex((35,24,17),'plain',256)
    scene=trimesh.Scene()
    def slug_shape(a):
        x,y,z=a
        # Broad sole, tapered tail, shaped tentacle stalks; directional forward +Z
        zshape=z*(.96+.09*math.sin(z*math.pi))
        return np.array([x*(1+.20*z),max(-.85,y),zshape])
    add(scene,mesh_uv_sphere([0,.051,-.04],[.099,.050,.19],body,warp=slug_shape),'pebbled_foot')
    add(scene,solid_sphere([0,.075,.125],[.075,.082,.097],light),'head')
    add(scene,solid_sphere([0,.041,.172],[.065,.044,.07],body),'mouth_bulge')
    # Spiraled shell is a true spatial volume, not a flat image.
    add(scene,mesh_uv_sphere([0,.169,-.061],[.095,.104,.103],shell,warp=lambda a: np.array([a[0]*(.96+.05*a[2]),a[1]*(1+.08*a[2]),a[2]])),'shell')
    # Big central shell whorl at either side; concentric 3D relief rings.
    for side in [-1,1]:
        for k in range(4):
            rr=.011+k*.013
            center=np.array([side*(.089+(.003 if k==0 else .001)),.182,-.066])
            ang=np.linspace(0,2*np.pi,64)
            pts=[center+np.array([side*.002*(math.cos(a)+k),rr*math.cos(a),rr*math.sin(a)]) for a in ang]
            add(scene,tapered_tube(pts,[.0017]*(len(pts)),shell,10),f'whorl_{side}_{k}')
    for side in [-1,1]:
        # Two true 3D eyestalks, with eye bulbs, and lower short feelers
        pts=[[side*.051,.113,.182],[side*.060,.143,.211],[side*.078,.184,.235],[side*.097,.206,.250]]
        add(scene,tapered_tube(pts,[.008,.007,.006,.005],light),f'eyestalk_{side}')
        add(scene,solid_sphere(pts[-1],[.013,.012,.012],light),f'eyebulb_{side}')
        add(scene,solid_sphere([pts[-1][0],pts[-1][1]+.002,pts[-1][2]+.009],[.005,.006,.005],dark),f'eye_{side}')
        pts2=[[side*.032,.085,.194],[side*.059,.086,.231],[side*.078,.087,.247]]
        add(scene,tapered_tube(pts2,[.005,.004,.002],light,12),f'feeler_{side}')
    # precise physical scale approx 37 cm long -> larger in AR than a real garden snail,
    # application per-species calibration scales down to 1/4.
    b=scene.export(file_type='glb')
    (out/filename).write_bytes(b)
    print(filename,len(b),'bytes',len(scene.geometry),'parts')

def ladybird():
    scene=trimesh.Scene()
    red=tex((199,36,20),'red'); black=tex((24,24,28),'skin'); dark=tex((41,36,34),'skin'); white=tex((224,214,189),'plain',256)
    add(scene,mesh_uv_sphere([0,.14,-.02],[.105,.114,.134],red),'polished_red_elytra')
    add(scene,solid_sphere([0,.069,-.008],[.104,.054,.13],black),'lower_body')
    add(scene,solid_sphere([0,.122,.112],[.071,.064,.056],black),'pronotum')
    add(scene,solid_sphere([0,.106,.159],[.039,.04,.046],black),'head')
    # black elytra seam and elevated spot shapes, mapped onto the domed shell.
    seam=[[0,.246,-.125+i*.006] for i in range(38)]
    add(scene,tapered_tube(seam,[.0018]*len(seam),black,12),'central_elytra_seam')
    for side in [-1,1]:
        for zi,xi in [(-.096,.057),(-.02,.070),(.053,.056)]:
            # Dome height ellipsoid top: y center .14 plus sqrt(1-(x/a)^2-(z/c)^2)*.114
            r=((xi/.105)**2+(zi+.02)**2/.134**2)
            y=.14+math.sqrt(max(.1,1-r))*.114
            add(scene,solid_sphere([side*xi,y,zi],[.019,.0045,.017],black),f'wing_spot_{side}_{zi}')
        for zi in (-.07,.07,.13):
            # 6 jointed legs with knees & little feet
            start=np.array([side*.075,.072,zi]);knee=np.array([side*.14,.063,zi+.025]);tip=np.array([side*.158,.004,zi+.043])
            add(scene,tapered_tube([start,knee,tip],[.006,.004,.002],black,12),f'leg_{side}_{zi}')
        add(scene,solid_sphere([side*.037,.164,.141],[.024,.021,.013],white),f'pronotum_white_{side}')
        add(scene,tapered_tube([[side*.028,.117,.184],[side*.035,.141,.201],[side*.041,.147,.217]],[.003,.002,.001],dark,10),f'antenna_{side}')
    b=scene.export(file_type='glb');(out/'ladybird-seven-spot.glb').write_bytes(b)
    print('ladybird-seven-spot.glb',len(b),'bytes',len(scene.geometry),'parts')

snail('snail-garden-snail.glb')
snail('snail-amber-snail.glb',True)
ladybird()
